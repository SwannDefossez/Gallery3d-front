function buildArtworkSeed(base: Omit<GalleryArtworkRecord, 'legacyId' | 'slug' | 'galleryKey' | 'stockTotal' | 'stockReserved' | 'stockSold' | 'status'>) {
  return {
    ...base,
    legacyId: base.id,
    slug: MAIN_GALLERY_SLUGS[base.debugNumber],
    galleryKey: 'main-gallery',
    stockTotal: MAIN_GALLERY_STOCK_TOTALS[base.debugNumber],
    stockReserved: 0,
    stockSold: 0,
    status: 'PUBLISHED' as const,
  };
}

